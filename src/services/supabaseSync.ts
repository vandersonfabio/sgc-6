/**
 * Non-destructive Write Capability Test against Supabase PostgreSQL:
 * 1. Attempts non-destructive test on auditoria_sistema or fallback to unidade.
 * 2. Confirms return of data and lack of RLS / permission denial.
 */
export async function testSupabaseWriteCapability(): Promise<{
  success: boolean;
  message: string;
  latencyMs?: number;
  code?: string;
  details?: string;
}> {
  const client = getSupabaseClient();
  if (!client) {
    return { success: false, message: 'Supabase não configurado.' };
  }

  const testLogId = `test_write_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;
  const start = performance.now();

  try {
    // 1. Try testing on auditoria_sistema
    const { error: insertErr } = await client.from('auditoria_sistema').insert({
      id_log: testLogId,
      acao: 'TESTE_CAPACIDADE_ESCRITA',
      tabela: 'sistema',
      id_operador: null,
      operador_nome: 'Teste Diagnóstico SGC-6',
      detalhes: { teste: 'Verificação não-destrutiva de permissão de escrita' },
      data_hora: new Date().toISOString(),
    });

    const latency = Math.round(performance.now() - start);

    if (!insertErr) {
      // Clean up test row
      await client.from('auditoria_sistema').delete().eq('id_log', testLogId);

      return {
        success: true,
        message: `Capacidade de escrita confirmada com sucesso (${latency}ms). O banco aceita INSERT e DELETE sem bloqueios.`,
        latencyMs: latency,
      };
    }

    // If auditoria_sistema has path / route error (PGRST125), test write on unidade as fallback
    if (insertErr.code === 'PGRST125' || insertErr.code === '42P01') {
      const tempUnitName = `__TEST_WRITE_${Date.now()}`;
      const { data: unitData, error: unitErr } = await client
        .from('unidade')
        .insert({ nome: tempUnitName, tipo_unidade: 'Setor' })
        .select('id_unidade')
        .single();

      if (!unitErr && unitData?.id_unidade) {
        await client.from('unidade').delete().eq('id_unidade', unitData.id_unidade);
        return {
          success: true,
          message: `Capacidade de escrita confirmada com sucesso via tabela de unidades (${latency}ms).`,
          latencyMs: latency,
        };
      }
    }

    console.error('[Supabase] Falha no teste de escrita:', insertErr);
    return {
      success: false,
      message: `Falha de escrita no banco: ${insertErr.message}`,
      code: insertErr.code,
      details: insertErr.details || insertErr.hint,
      latencyMs: latency,
    };
  } catch (err: any) {
    console.error('[Supabase] Exceção no teste de escrita:', err);
    return {
      success: false,
      message: `Erro na execução do teste de escrita: ${err.message}`,
    };
  }
}

export interface DiagnosticStep {
  name: string;
  category: 'connection' | 'tables' | 'permissions' | 'catalog' | 'relationships';
  status: 'pending' | 'success' | 'warning' | 'error';
  message: string;
  details?: string;
  latencyMs?: number;
}

export interface FullDiagnosticReport {
  timestamp: string;
  overallSuccess: boolean;
  canRead: boolean;
  canWrite: boolean;
  tablesFound: number;
  totalTables: number;
  steps: DiagnosticStep[];
}

/**
 * Runs a thorough 5-stage diagnostic test against the Supabase PostgreSQL database:
 * 1. Connectivity & Latency test (Read/Ping)
 * 2. Table Schema Existence (verifies all 12 core tables)
 * 3. Write/Read Permissions (tests non-destructive INSERT & DELETE)
 * 4. Structural Base Catalog (checks if basic units & item types exist)
 * 5. Identity PK & Foreign Key Validation (verifies insertion without ID and relation between item_patrimonio and detalhe_arma)
 */
export async function runSupabaseFullDiagnostics(): Promise<FullDiagnosticReport> {
  const steps: DiagnosticStep[] = [];
  const client = getSupabaseClient();

  if (!client) {
    steps.push({
      name: 'Inicialização do Cliente',
      category: 'connection',
      status: 'error',
      message: 'Supabase não está configurado. Insira a URL e a Publishable/Anon Key.',
    });
    return {
      timestamp: new Date().toISOString(),
      overallSuccess: false,
      canRead: false,
      canWrite: false,
      tablesFound: 0,
      totalTables: 12,
      steps,
    };
  }

  let canRead = false;
  let canWrite = false;
  let tablesFound = 0;
  const coreTables = [
    'unidade',
    'policial',
    'operador_sistema',
    'tipo_material',
    'item_patrimonio',
    'detalhe_arma',
    'detalhe_colete',
    'estoque_lote',
    'cautela',
    'cautela_item',
    'alocacao_unidade',
    'auditoria_sistema',
  ];

  // Stage 1: Ping & Connectivity (Read)
  const startPing = performance.now();
  try {
    const { error: pingErr } = await client.from('unidade').select('count', { count: 'exact', head: true });
    const pingLatency = Math.round(performance.now() - startPing);

    if (pingErr && pingErr.code !== '42P01' && pingErr.code !== 'PGRST116' && pingErr.code !== '42501') {
      steps.push({
        name: 'Conexão e Leitura (API REST / PostgREST)',
        category: 'connection',
        status: 'error',
        message: `Falha na conexão de leitura: ${pingErr.message}`,
        details: `Código: ${pingErr.code || 'N/A'}. Verifique se a URL do projeto e a chave estão corretas.`,
        latencyMs: pingLatency,
      });
    } else {
      steps.push({
        name: 'Conexão e Leitura (API REST / PostgREST)',
        category: 'connection',
        status: 'success',
        message: `API conectada e acessível para leitura (${pingLatency}ms)`,
        latencyMs: pingLatency,
      });
    }
  } catch (e: any) {
    steps.push({
      name: 'Conexão e Leitura',
      category: 'connection',
      status: 'error',
      message: `Erro de rede ou URL inválida: ${e.message}`,
    });
  }

  // Stage 2: Table Existence & Read Test
  const missingTables: string[] = [];
  const tableErrors: { table: string; code?: string; message: string }[] = [];
  for (const table of coreTables) {
    try {
      const { error } = await client.from(table).select('*').limit(1);
      if (error) {
        tableErrors.push({ table, code: error.code, message: error.message });
        if (
          error.code === '42P01' ||
          error.code === 'PGRST204' ||
          error.code === 'PGRST200' ||
          error.code === 'PGRST205' ||
          error.message.includes('relation') ||
          error.message.includes('does not exist') ||
          error.message.includes('schema cache')
        ) {
          missingTables.push(table);
        } else {
          tablesFound++;
        }
      } else {
        tablesFound++;
        canRead = true;
      }
    } catch (e: any) {
      missingTables.push(table);
      tableErrors.push({ table, message: e.message });
    }
  }

  if (missingTables.length === 0) {
    steps.push({
      name: 'Esquema de Tabelas (DDL no PostgreSQL)',
      category: 'tables',
      status: 'success',
      message: `Todas as 12 tabelas principais existem no PostgreSQL`,
      details: coreTables.join(', '),
    });
  } else if (tablesFound > 0) {
    steps.push({
      name: 'Esquema de Tabelas (DDL no PostgreSQL)',
      category: 'tables',
      status: 'warning',
      message: `${tablesFound} de ${coreTables.length} tabelas encontradas. Faltam: ${missingTables.join(', ')}`,
      details: 'Execute o script SQL completo no SQL Editor do Supabase.',
    });
  } else {
    steps.push({
      name: 'Esquema de Tabelas (DDL no PostgreSQL)',
      category: 'tables',
      status: 'error',
      message: 'Nenhuma tabela foi encontrada no cache do Supabase.',
      details: 'Cole e execute o Script SQL Completo no SQL Editor do Supabase.',
    });
  }

  // Stage 3: Live Non-Destructive Write Test
  const writeRes = await testSupabaseWriteCapability();
  if (writeRes.success) {
    canWrite = true;
    steps.push({
      name: 'Capacidade de Gravação Real (Escrita & Exclusão)',
      category: 'permissions',
      status: 'success',
      message: writeRes.message,
      latencyMs: writeRes.latencyMs,
    });
  } else {
    steps.push({
      name: 'Capacidade de Gravação Real (Escrita & Exclusão)',
      category: 'permissions',
      status: 'error',
      message: writeRes.message,
      details: writeRes.details ? `Detalhes: ${writeRes.details}` : undefined,
    });
  }

  // Stage 4: Base Catalog & Foreign Key Pre-requisites
  try {
    const { count: unitCount } = await client.from('unidade').select('*', { count: 'exact', head: true });
    const { count: typeCount } = await client.from('tipo_material').select('*', { count: 'exact', head: true });
    const { count: opCount } = await client.from('operador_sistema').select('*', { count: 'exact', head: true });

    if ((unitCount || 0) > 0 && (typeCount || 0) > 0) {
      steps.push({
        name: 'Catálogo Base (Unidades e Tipos de Materiais)',
        category: 'catalog',
        status: 'success',
        message: `Catálogo pronto: ${unitCount} unidade(s), ${typeCount} tipo(s) de material, ${opCount || 0} operador(es)`,
        details: 'Chaves estrangeiras (Foreign Keys) validadas para novos cadastros.',
      });
    } else {
      steps.push({
        name: 'Catálogo Base (Unidades e Tipos de Materiais)',
        category: 'catalog',
        status: 'warning',
        message: `Catálogo incompleto: ${unitCount || 0} unidades, ${typeCount || 0} tipos de materiais`,
        details: 'Execute a sincronização de dados ou o script SQL com os dados estruturais do 6º BPM.',
      });
    }
  } catch (e: any) {
    steps.push({
      name: 'Catálogo Base',
      category: 'catalog',
      status: 'warning',
      message: 'Não foi possível verificar as tabelas de catálogo base.',
      details: e.message,
    });
  }

  // Stage 5: Identity PK & Relationship Test (Armas -> DetalheArma)
  try {
    const testSerie = `TEST-DIAG-${Date.now()}`;
    // 1. Insert item_patrimonio without id_item
    const { data: testItem, error: testItemErr } = await client
      .from('item_patrimonio')
      .insert({
        modulo: 'Armas',
        tipo_item: 'Pistola',
        marca: 'Taurus',
        modelo: 'TS9',
        numero_serie: testSerie,
        status: 'Disponível',
        observacao: 'Registro temporário de validação diagnóstica',
      })
      .select()
      .single();

    if (testItemErr) {
      steps.push({
        name: 'Validação de Chave Primária IDENTITY e Relacionamento de Armas',
        category: 'relationships',
        status: 'error',
        message: `Falha ao inserir item_patrimonio sem ID: ${testItemErr.message}`,
        details: `Código: ${testItemErr.code}. Verifique se a coluna é GENERATED AS IDENTITY.`,
      });
    } else if (testItem?.id_item) {
      const generatedId = Number(testItem.id_item);

      // 2. Insert detalhe_arma with generated id_item as FK
      const { error: testDetErr } = await client.from('detalhe_arma').insert({
        id_item: generatedId,
        calibre: '9mm',
        brasao_gravado: true,
        qtd_carregadores: 3,
        carregadores_coincidem_numeracao: true,
      });

      if (testDetErr) {
        steps.push({
          name: 'Validação de Chave Primária IDENTITY e Relacionamento de Armas',
          category: 'relationships',
          status: 'error',
          message: `Item inserido (ID: ${generatedId}), mas falhou ao criar detalhe_arma: ${testDetErr.message}`,
        });
      } else {
        steps.push({
          name: 'Validação de Chave Primária IDENTITY e Relacionamento de Armas',
          category: 'relationships',
          status: 'success',
          message: `Fluxo relacional validado: item_patrimonio (ID gerado: ${generatedId}) -> detalhe_arma vinculado com sucesso`,
        });
      }

      // Cleanup test item (cascades to detalhe_arma)
      await client.from('item_patrimonio').delete().eq('id_item', generatedId);
    }
  } catch (err: any) {
    steps.push({
      name: 'Validação de Chave Primária IDENTITY e Relacionamentos',
      category: 'relationships',
      status: 'warning',
      message: `Não foi possível rodar o teste relacional completo: ${err.message}`,
    });
  }

  const overallSuccess = canRead && canWrite && tablesFound >= coreTables.length;

  return {
    timestamp: new Date().toISOString(),
    overallSuccess,
    canRead,
    canWrite,
    tablesFound,
    totalTables: coreTables.length,
    steps,
  };
}

