/**
 * Pushes a single item and its specialized details (e.g. Arma, Colete, VTR) to Supabase.
 * - DOES NOT send identity id_item on INSERT.
 * - Extracts definitive id_item generated by PostgreSQL.
 * - Uses definitive id_item for inserting/upserting specialized details (detalhe_arma, etc.).
 * - Verifies and resolves foreign key id_tipo_material without guessing.
 */
export async function pushItemToSupabase(
  item: ItemPatrimonio,
  detalhes?: {
    arma?: DetalheArma;
    colete?: DetalheColete;
    impo?: DetalheImpo;
    comunicacao?: DetalheComunicacao;
    viatura?: DetalheViatura;
    informatica?: DetalheInformatica;
  },
  tipoMaterial?: TipoMaterial
): Promise<SyncOperationResult<{ id_item: number }>> {
  const client = getSupabaseClient();
  if (!client) {
    return { success: false, error: 'Supabase não conectado. Configure as credenciais do projeto.' };
  }

  try {
    // 1. Resolve Foreign Key: id_tipo_material
    let resolvedTipoId: number | null = null;

    if (item.id_tipo_material) {
      // Verify if specified id_tipo_material exists in Supabase
      const { data: tipoRow } = await client
        .from('tipo_material')
        .select('id_tipo_material')
        .eq('id_tipo_material', item.id_tipo_material)
        .maybeSingle();

      if (tipoRow?.id_tipo_material) {
        resolvedTipoId = Number(tipoRow.id_tipo_material);
      }
    }

    // If not resolved by ID, attempt lookup by natural key: nome
    if (!resolvedTipoId && item.tipo_item) {
      const { data: tipoByName } = await client
        .from('tipo_material')
        .select('id_tipo_material')
        .ilike('nome', item.tipo_item.trim())
        .maybeSingle();

      if (tipoByName?.id_tipo_material) {
        resolvedTipoId = Number(tipoByName.id_tipo_material);
      }
    }

    // If tipoMaterial payload was explicitly provided and still not in DB, insert it first
    if (!resolvedTipoId && tipoMaterial) {
      const tipoRes = await pushTipoMaterialToSupabase(tipoMaterial);
      if (tipoRes.success && tipoRes.definitiveId) {
        resolvedTipoId = Number(tipoRes.definitiveId);
      }
    }

    // If id_tipo_material could not be resolved and is required by schema integrity
    if (!resolvedTipoId && item.id_tipo_material) {
      const msg = `Tipo de material referenciado (ID: ${item.id_tipo_material}, Nome: "${item.tipo_item}") não foi encontrado no banco Supabase. Cadastre ou sincronize o catálogo de materiais primeiro.`;
      console.error('[Supabase] Falha de Chave Estrangeira:', msg);
      return { success: false, error: msg };
    }

    // 2. Check if item already exists in Supabase by natural unique keys (numero_serie or numero_tombo)
    let existingDbId: number | null = null;

    if (item.numero_serie && item.numero_serie.trim()) {
      const { data: existingBySerie } = await client
        .from('item_patrimonio')
        .select('id_item')
        .eq('numero_serie', item.numero_serie.trim())
        .maybeSingle();

      if (existingBySerie?.id_item) {
        existingDbId = Number(existingBySerie.id_item);
      }
    }

    if (!existingDbId && item.numero_tombo && item.numero_tombo.trim()) {
      const { data: existingByTombo } = await client
        .from('item_patrimonio')
        .select('id_item')
        .eq('numero_tombo', item.numero_tombo.trim())
        .maybeSingle();

      if (existingByTombo?.id_item) {
        existingDbId = Number(existingByTombo.id_item);
      }
    }

    let definitiveId: number;

    const basePayload = {
      id_tipo_material: resolvedTipoId || null,
      modulo: item.modulo,
      tipo_item: item.tipo_item,
      marca: item.marca || null,
      modelo: item.modelo || null,
      numero_serie: item.numero_serie || null,
      numero_tombo: item.numero_tombo || null,
      status: item.status,
      observacao: item.observacao || null,
    };

    if (existingDbId) {
      // UPDATE existing item (DO NOT pass id_item in update body)
      const { data: updatedItem, error: updateErr } = await client
        .from('item_patrimonio')
        .update(basePayload)
        .eq('id_item', existingDbId)
        .select()
        .single();

      if (updateErr) {
        console.error('[Supabase] Falha ao atualizar item_patrimonio:', updateErr);
        return {
          success: false,
          error: `Falha ao atualizar item no Supabase: ${updateErr.message}`,
          code: updateErr.code,
          details: updateErr.details,
          hint: updateErr.hint,
        };
      }
      definitiveId = Number(updatedItem.id_item);
    } else {
      // INSERT new item (PostgreSQL IDENTITY will generate the ID)
      const { data: insertedItem, error: insertErr } = await client
        .from('item_patrimonio')
        .insert(basePayload)
        .select()
        .single();

      if (insertErr) {
        console.error('[Supabase] Falha ao inserir item_patrimonio:', insertErr);
        return {
          success: false,
          error: `Falha ao inserir item no Supabase: ${insertErr.message}`,
          code: insertErr.code,
          details: insertErr.details,
          hint: insertErr.hint,
        };
      }

      if (!insertedItem?.id_item) {
        const msg = 'PostgreSQL não retornou o id_item gerado após a inserção.';
        console.error('[Supabase] Erro de retorno:', msg);
        return { success: false, error: msg };
      }

      definitiveId = Number(insertedItem.id_item);
    }

    // 3. Upsert specialized details using the DEFINITIVE id_item
    if (detalhes?.arma) {
      const { error: armaErr } = await client.from('detalhe_arma').upsert({
        id_item: definitiveId,
        calibre: detalhes.arma.calibre,
        numero_sigma: detalhes.arma.numero_sigma || null,
        brasao_gravado: detalhes.arma.brasao_gravado ?? true,
        qtd_carregadores: detalhes.arma.qtd_carregadores ?? 2,
        carregadores_coincidem_numeracao: detalhes.arma.carregadores_coincidem_numeracao ?? false,
      }, { onConflict: 'id_item' });

      if (armaErr) {
        console.error('[Supabase] Falha ao persistir detalhe_arma:', armaErr);
        return {
          success: false,
          error: `Falha ao persistir especificações da arma: ${armaErr.message}`,
          code: armaErr.code,
          details: armaErr.details,
          hint: armaErr.hint,
        };
      }
    }

    if (detalhes?.colete) {
      const { error: colErr } = await client.from('detalhe_colete').upsert({
        id_item: definitiveId,
        genero: detalhes.colete.genero || 'Masculino',
        tamanho: detalhes.colete.tamanho || 'G',
        nivel_protecao: detalhes.colete.nivel_protecao || 'III-A',
        data_validade: detalhes.colete.data_validade,
      }, { onConflict: 'id_item' });

      if (colErr) {
        console.error('[Supabase] Falha ao persistir detalhe_colete:', colErr);
        return { success: false, error: `Falha ao persistir colete: ${colErr.message}` };
      }
    }

    if (detalhes?.impo) {
      const { error: impoErr } = await client.from('detalhe_impo').upsert({
        id_item: definitiveId,
        data_validade: detalhes.impo.data_validade || null,
      }, { onConflict: 'id_item' });

      if (impoErr) {
        console.error('[Supabase] Falha ao persistir detalhe_impo:', impoErr);
        return { success: false, error: `Falha ao persistir IMPO: ${impoErr.message}` };
      }
    }

    if (detalhes?.comunicacao) {
      const { error: comErr } = await client.from('detalhe_comunicacao').upsert({
        id_item: definitiveId,
        imei_mac: detalhes.comunicacao.imei_mac || null,
        numero_linha: detalhes.comunicacao.numero_linha || null,
      }, { onConflict: 'id_item' });

      if (comErr) {
        console.error('[Supabase] Falha ao persistir detalhe_comunicacao:', comErr);
        return { success: false, error: `Falha ao persistir equipamento de comunicação: ${comErr.message}` };
      }
    }

    if (detalhes?.viatura) {
      const safePlaca = (detalhes.viatura.placa || `PMR-${definitiveId}`).trim().toUpperCase();
      const safePrefixo = (detalhes.viatura.prefixo?.trim() || `VTR-${safePlaca.replace(/[^a-zA-Z0-9]/g, '')}`).toUpperCase();
      const { error: vtrErr } = await client.from('detalhe_viatura').upsert({
        id_item: definitiveId,
        placa: safePlaca,
        prefixo: safePrefixo,
        renavam: detalhes.viatura.renavam?.trim() || null,
        chassi: detalhes.viatura.chassi?.trim() || null,
      }, { onConflict: 'id_item' });

      if (vtrErr) {
        console.error('[Supabase] Falha ao persistir detalhe_viatura:', vtrErr);
        return { success: false, error: `Falha ao persistir viatura: ${vtrErr.message}` };
      }
    }

    if (detalhes?.informatica) {
      const { error: infErr } = await client.from('detalhe_informatica').upsert({
        id_item: definitiveId,
        configuracao_resumida: detalhes.informatica.configuracao_resumida || null,
      }, { onConflict: 'id_item' });

      if (infErr) {
        console.error('[Supabase] Falha ao persistir detalhe_informatica:', infErr);
        return { success: false, error: `Falha ao persistir TI: ${infErr.message}` };
      }
    }

    return {
      success: true,
      data: { id_item: definitiveId },
      definitiveId,
    };
  } catch (err: any) {
    console.error('[Supabase] Exceção ao persistir item:', err);
    return {
      success: false,
      error: err.message || 'Exceção não tratada na gravação do item.',
    };
  }
}

/**
 * Deletes an item from Supabase (cascades to detalhe_*).
 */
export async function deleteItemFromSupabase(id_item: number): Promise<SyncOperationResult> {
  const client = getSupabaseClient();
  if (!client) return { success: false, error: 'Supabase não conectado' };

  try {
    const { error } = await client.from('item_patrimonio').delete().eq('id_item', id_item);
    if (error) {
      console.error('[Supabase] Falha ao excluir item_patrimonio:', error);
      return { success: false, error: error.message, code: error.code, details: error.details };
    }
    return { success: true };
  } catch (err: any) {
    console.error('[Supabase] Exceção ao excluir item:', err);
    return { success: false, error: err.message };
  }
}

/**
 * Pushes a Policial to Supabase.
 * - Uses matricula and id_policial as lookups.
 * - Does not send id_policial on INSERT.
 * - Validates id_unidade_lotacao.
 */
export async function pushPolicialToSupabase(policial: Policial): Promise<SyncOperationResult<{ id_policial: number }>> {
  const client = getSupabaseClient();
  if (!client) return { success: false, error: 'Supabase não conectado' };

  try {
    // 1. Resolve unit foreign key (id_unidade_lotacao / id_unidade)
    let resolvedUnidadeId: number | null = null;
    const targetUnitId = policial.id_unidade_lotacao || policial.id_unidade;

    if (targetUnitId) {
      resolvedUnidadeId = Number(targetUnitId);
      // Verify that this unit exists in database
      const { data: unitRow } = await client
        .from('unidade')
        .select('id_unidade')
        .eq('id_unidade', resolvedUnidadeId)
        .maybeSingle();

      if (!unitRow?.id_unidade) {
        // If not found by ID, fallback to first unit in database
        const { data: firstUnit } = await client
          .from('unidade')
          .select('id_unidade')
          .order('id_unidade', { ascending: true })
          .limit(1)
          .maybeSingle();

        resolvedUnidadeId = firstUnit?.id_unidade ? Number(firstUnit.id_unidade) : null;
      }
    } else {
      const { data: firstUnit } = await client
        .from('unidade')
        .select('id_unidade')
        .order('id_unidade', { ascending: true })
        .limit(1)
        .maybeSingle();

      resolvedUnidadeId = firstUnit?.id_unidade ? Number(firstUnit.id_unidade) : null;
    }

    // 2. Check if policial already exists by id_policial OR by matricula
    let existingDbId: number | null = null;

    if (policial.id_policial) {
      const { data: existingById } = await client
        .from('policial')
        .select('id_policial')
        .eq('id_policial', policial.id_policial)
        .maybeSingle();
      if (existingById?.id_policial) {
        existingDbId = Number(existingById.id_policial);
      }
    }

    if (!existingDbId && policial.matricula && policial.matricula.trim()) {
      const { data: existingPol } = await client
        .from('policial')
        .select('id_policial')
        .eq('matricula', policial.matricula.trim())
        .maybeSingle();
      if (existingPol?.id_policial) {
        existingDbId = Number(existingPol.id_policial);
      }
    }

    const payload = {
      matricula: policial.matricula.trim(),
      patente: policial.patente,
      nome_guerra: policial.nome_guerra,
      nome_completo: policial.nome_completo,
      id_unidade_lotacao: resolvedUnidadeId,
      status: policial.status,
      contato: policial.contato || null,
      telefone: policial.telefone || null,
      email: policial.email || null,
    };

    let definitiveId: number;

    if (existingDbId) {
      // UPDATE
      const { data: updated, error: updateErr } = await client
        .from('policial')
        .update(payload)
        .eq('id_policial', existingDbId)
        .select()
        .single();

      if (updateErr) {
        console.error('[Supabase] Falha ao atualizar policial:', updateErr);
        return { success: false, error: updateErr.message, code: updateErr.code, details: updateErr.details };
      }
      definitiveId = Number(updated.id_policial);
    } else {
      // INSERT (without id_policial)
      const { data: inserted, error: insertErr } = await client
        .from('policial')
        .insert(payload)
        .select()
        .single();

      if (insertErr) {
        // If failed due to duplicate key (e.g. sequence collision or unique matricula)
        if (insertErr.code === '23505') {
          const { data: retryPol } = await client
            .from('policial')
            .select('id_policial')
            .eq('matricula', policial.matricula.trim())
            .maybeSingle();

          if (retryPol?.id_policial) {
            const { data: updatedRetry, error: retryUpdErr } = await client
              .from('policial')
              .update(payload)
              .eq('id_policial', retryPol.id_policial)
              .select()
              .single();

            if (!retryUpdErr && updatedRetry?.id_policial) {
              return {
                success: true,
                data: { id_policial: Number(updatedRetry.id_policial) },
                definitiveId: Number(updatedRetry.id_policial),
              };
            }
          }
        }
        console.error('[Supabase] Falha ao inserir policial:', insertErr);
        return { success: false, error: insertErr.message, code: insertErr.code, details: insertErr.details };
      }
      definitiveId = Number(inserted.id_policial);
    }

    return {
      success: true,
      data: { id_policial: definitiveId },
      definitiveId,
    };
  } catch (err: any) {
    console.error('[Supabase] Exceção ao persistir policial:', err);
    return { success: false, error: err.message };
  }
}

/**
 * Pushes an Operador do Sistema to Supabase.
 * - Handles FK resolution with policial table.
 * - Upserts safely by id_policial, email, or id_operador to prevent 23505 duplicate key errors.
 */
export async function pushOperadorToSupabase(
  op: OperadorSistema,
  mappedPolicialId?: number
): Promise<SyncOperationResult<{ id_operador: string }>> {
  const client = getSupabaseClient();
  if (!client) return { success: false, error: 'Supabase não conectado' };

  try {
    const targetPolicialId = mappedPolicialId || op.id_policial;

    // 1. Verify that target policial exists in Supabase
    const { data: polRow } = await client
      .from('policial')
      .select('id_policial')
      .eq('id_policial', targetPolicialId)
      .maybeSingle();

    if (!polRow?.id_policial) {
      const msg = `Policial com ID ${targetPolicialId} não encontrado no Supabase para vincular ao operador ${op.email}.`;
      console.warn('[Supabase] Aviso de FK em operador:', msg);
      return { success: false, error: msg };
    }

    const safePolicialId = Number(polRow.id_policial);
    const safeEmail = (op.email && op.email.trim()) || `operador_${safePolicialId}@pm.rn.gov.br`;

    // 2. Check for existing operador by id_policial, email, or id_operador
    let existingDbOp: any = null;

    const { data: byPol } = await client
      .from('operador_sistema')
      .select('*')
      .eq('id_policial', safePolicialId)
      .maybeSingle();

    if (byPol) {
      existingDbOp = byPol;
    } else {
      const { data: byEmail } = await client
        .from('operador_sistema')
        .select('*')
        .ilike('email', safeEmail)
        .maybeSingle();

      if (byEmail) {
        existingDbOp = byEmail;
      } else if (op.id_operador) {
        const { data: byId } = await client
          .from('operador_sistema')
          .select('*')
          .eq('id_operador', op.id_operador)
          .maybeSingle();

        if (byId) {
          existingDbOp = byId;
        }
      }
    }

    if (existingDbOp) {
      // UPDATE
      const { data: updated, error: updErr } = await client
        .from('operador_sistema')
        .update({
          id_policial: safePolicialId,
          perfil_acesso: op.perfil_acesso,
          status: op.status,
          email: safeEmail,
          senha: op.senha || existingDbOp.senha || '123',
        })
        .eq('id_operador', existingDbOp.id_operador)
        .select()
        .single();

      if (updErr) {
        console.error('[Supabase] Falha ao atualizar operador_sistema:', updErr);
        return { success: false, error: updErr.message, code: updErr.code };
      }

      // Auto-sync credentials with Supabase Auth (auth.users)
      syncOperadorAuthUser(safeEmail, op.senha || existingDbOp.senha || '123', {
        id_policial: safePolicialId,
        perfil: op.perfil_acesso,
      }).catch(() => {});

      return {
        success: true,
        data: { id_operador: updated.id_operador },
        definitiveId: updated.id_operador,
      };
    } else {
      // INSERT
      const insertPayload: any = {
        id_policial: safePolicialId,
        perfil_acesso: op.perfil_acesso,
        status: op.status,
        email: safeEmail,
        senha: op.senha || '123',
      };
      if (op.id_operador) {
        insertPayload.id_operador = op.id_operador;
      }

      const { data: inserted, error: insErr } = await client
        .from('operador_sistema')
        .insert(insertPayload)
        .select()
        .single();

      if (insErr) {
        console.error('[Supabase] Falha ao inserir operador_sistema:', insErr);
        return { success: false, error: insErr.message, code: insErr.code };
      }

      // Auto-sync credentials with Supabase Auth (auth.users)
      syncOperadorAuthUser(safeEmail, op.senha || '123', {
        id_policial: safePolicialId,
        perfil: op.perfil_acesso,
      }).catch(() => {});

      return {
        success: true,
        data: { id_operador: inserted.id_operador },
        definitiveId: inserted.id_operador,
      };
    }
  } catch (err: any) {
    console.error('[Supabase] Exceção ao persistir operador:', err);
    return { success: false, error: err.message };
  }
}

/**
 * Auto-provisions or syncs the user in Supabase Auth (auth.users)
 * so the operator can log in seamlessly with JWT tokens under RLS.
 */
export async function syncOperadorAuthUser(
  email: string,
  senha?: string,
  metadata?: { id_policial?: number; perfil?: string }
): Promise<{ success: boolean; error?: string }> {
  const client = getSupabaseClient();
  if (!client || !email) return { success: false, error: 'Supabase não conectado' };

  try {
    const safeEmail = email.trim().toLowerCase();
    const safePassword = senha?.trim() || '123';

    // 1. Attempt signUp on Supabase Auth
    const { data, error: signUpErr } = await client.auth.signUp({
      email: safeEmail,
      password: safePassword,
      options: {
        data: {
          id_policial: metadata?.id_policial,
          perfil: metadata?.perfil,
          origem: 'SGC-6 6º BPM',
        },
      },
    });

    if (!signUpErr) {
      console.log(`[Supabase Auth] Usuário '${safeEmail}' provisionado com sucesso em auth.users.`);
      return { success: true };
    }

    // 2. If user already registered in auth.users, that's fine
    if (
      signUpErr.message?.toLowerCase().includes('already registered') ||
      signUpErr.message?.toLowerCase().includes('already exists') ||
      signUpErr.status === 422
    ) {
      return { success: true };
    }

    console.warn(`[Supabase Auth] Aviso ao provisionar '${safeEmail}':`, signUpErr.message);
    return { success: false, error: signUpErr.message };
  } catch (err: any) {
    console.warn('[Supabase Auth] Exceção ao sincronizar credenciais:', err);
    return { success: false, error: err.message };
  }
}

/**
 * Bulk syncs all operators to Supabase Auth.
 */
export async function syncAllOperadoresToAuth(
  operadores: OperadorSistema[],
  policiais: Policial[]
): Promise<{ success: boolean; count: number; errors: string[] }> {
  const errors: string[] = [];
  let count = 0;

  for (const op of operadores) {
    if (!op.email) continue;
    const pol = policiais.find((p) => p.id_policial === op.id_policial);
    const res = await syncOperadorAuthUser(op.email, op.senha, {
      id_policial: op.id_policial,
      perfil: op.perfil_acesso,
    });
    if (res.success) {
      count++;
    } else if (res.error) {
      errors.push(`${pol ? pol.nome_guerra : op.email}: ${res.error}`);
    }
  }

  return { success: errors.length === 0, count, errors };
}

