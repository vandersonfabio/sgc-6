/**
 * Pushes a batch or single lote (munições, volumes) to Supabase.
 * - Checks by primary id_lote first, then falls back to composite keys.
 * - Extracts definitive id_lote generated by PostgreSQL.
 */
export async function pushLoteToSupabase(lote: EstoqueLote): Promise<SyncOperationResult<{ id_lote: number }>> {
  const client = getSupabaseClient();
  if (!client) return { success: false, error: 'Supabase não conectado' };

  try {
    // 1. Resolve tipo_material
    let resolvedTipoId: number | null = null;
    if (lote.id_tipo_material) {
      const { data: tipoRow } = await client
        .from('tipo_material')
        .select('id_tipo_material')
        .eq('id_tipo_material', lote.id_tipo_material)
        .maybeSingle();

      if (tipoRow?.id_tipo_material) {
        resolvedTipoId = Number(tipoRow.id_tipo_material);
      }
    }

    if (!resolvedTipoId && lote.tipo_item) {
      const { data: tipoByName } = await client
        .from('tipo_material')
        .select('id_tipo_material')
        .ilike('nome', lote.tipo_item.trim())
        .maybeSingle();

      if (tipoByName?.id_tipo_material) {
        resolvedTipoId = Number(tipoByName.id_tipo_material);
      }
    }

    // 2. Check for existing lote: first by id_lote, then by composite keys
    let existingDbId: number | null = null;
    if (lote.id_lote) {
      const { data: byId } = await client
        .from('estoque_lote')
        .select('id_lote')
        .eq('id_lote', lote.id_lote)
        .maybeSingle();
      if (byId?.id_lote) {
        existingDbId = Number(byId.id_lote);
      }
    }

    if (!existingDbId) {
      let existingQuery = client.from('estoque_lote').select('id_lote').eq('tipo_item', lote.tipo_item);
      if (lote.calibre) existingQuery = existingQuery.eq('calibre', lote.calibre);
      if (lote.lote_fabricacao) existingQuery = existingQuery.eq('lote_fabricacao', lote.lote_fabricacao);

      const { data: existingLote } = await existingQuery.maybeSingle();
      if (existingLote?.id_lote) {
        existingDbId = Number(existingLote.id_lote);
      }
    }

    const payload = {
      id_tipo_material: resolvedTipoId,
      modulo: lote.modulo,
      tipo_item: lote.tipo_item,
      marca: lote.marca || null,
      modelo: lote.modelo || null,
      calibre: lote.calibre || null,
      lote_fabricacao: lote.lote_fabricacao || null,
      data_validade: lote.data_validade || null,
      quantidade_atual: Math.max(0, lote.quantidade_atual),
      observacao: lote.observacao || null,
    };

    let definitiveId: number;

    if (existingDbId) {
      const { data: updated, error: updateErr } = await client
        .from('estoque_lote')
        .update(payload)
        .eq('id_lote', existingDbId)
        .select()
        .single();

      if (updateErr) {
        console.error('[Supabase] Falha ao atualizar estoque_lote:', updateErr);
        return { success: false, error: updateErr.message, code: updateErr.code };
      }
      definitiveId = Number(updated.id_lote);
    } else {
      const { data: inserted, error: insertErr } = await client
        .from('estoque_lote')
        .insert(payload)
        .select()
        .single();

      if (insertErr) {
        console.error('[Supabase] Falha ao inserir estoque_lote:', insertErr);
        return { success: false, error: insertErr.message, code: insertErr.code };
      }
      definitiveId = Number(inserted.id_lote);
    }

    return {
      success: true,
      data: { id_lote: definitiveId },
      definitiveId,
    };
  } catch (err: any) {
    console.error('[Supabase] Exceção ao persistir lote:', err);
    return { success: false, error: err.message };
  }
}

