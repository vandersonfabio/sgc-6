/**
 * Realtime Subscription for automatic multi-user bidirectional sync.
 * Listens to all changes in the database (INSERT, UPDATE, DELETE) across all public tables
 * and triggers the callback with debounce.
 */
let realtimeChannelInstance: any = null;
let realtimeDebounceTimer: any = null;

export function initSupabaseRealtime(onDatabaseChanged: () => void): () => void {
  const client = getSupabaseClient();
  if (!client) return () => {};

  if (realtimeChannelInstance) {
    try {
      client.removeChannel(realtimeChannelInstance);
    } catch {}
    realtimeChannelInstance = null;
  }

  try {
    realtimeChannelInstance = client
      .channel('sgc6_live_database_changes')
      .on(
        'postgres_changes',
        {
          event: '*',
          schema: 'public',
        },
        (payload: any) => {
          console.log(`[Supabase Realtime] Alteração recebida em '${payload.table}' [${payload.eventType}]`);
          if (realtimeDebounceTimer) clearTimeout(realtimeDebounceTimer);
          realtimeDebounceTimer = setTimeout(() => {
            onDatabaseChanged();
          }, 350);
        }
      )
      .subscribe((status: string, err: any) => {
        if (status === 'SUBSCRIBED') {
          console.log('[Supabase Realtime] Canal conectado com sucesso: ouvindo alterações no 6º BPM em tempo real.');
        } else if (status === 'CHANNEL_ERROR') {
          console.warn('[Supabase Realtime] Aviso no canal Realtime:', err);
        }
      });
  } catch (e) {
    console.warn('[Supabase Realtime] Não foi possível registrar listener:', e);
  }

  return () => {
    if (realtimeChannelInstance && client) {
      try {
        client.removeChannel(realtimeChannelInstance);
      } catch {}
      realtimeChannelInstance = null;
    }
  };
}

