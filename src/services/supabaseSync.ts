/**
 * Pushes a Cautela and its items/lotes to Supabase.
 * - Inserts or updates Cautela.
 * - Extracts definitive id_cautela and inserts into cautela_item and cautela_estoque.
 * - Updates item_patrimonio status to 'Cautelado'.
 * - Synchronizes deducted stock on estoque_lote.
 */
export async function pushCautelaToSupabase(
  cautela: Cautela,
  itens: CautelaItem[] = [],
  lotes: CautelaEstoque[] = [],
  lotesSaldosRestantes?: Array<{ id_lote: number; quantidade_atual: number }>
): Promise<SyncOperationResult<{ id_cautela: number }>> {
  const client = getSupabaseClient();
  if (!client) return { success: false, error: 'Supabase não conectado' };

  try {
    // 1. Validate Policial Foreign Key
    const { data: polRow } = await client
      .from('policial')
      .select('id_policial')
      .eq('id_policial', cautela.id_policial)
      .maybeSingle();

    if (!polRow) {
      const msg = `Policial de destino (ID: ${cautela.id_policial}) não existe no Supabase. Sincronize o efetivo primeiro.`;
      console.error('[Supabase] Falha de FK:', msg);
      return { success: false, error: msg };
    }

    // 2. Check if Cautela already exists
    let existingCautelaId: number | null = null;
    if (cautela.id_cautela) {
      const { data: cCheck } = await client
        .from('cautela')
        .select('id_cautela')
        .eq('id_cautela', cautela.id_cautela)
        .maybeSingle();
      if (cCheck?.id_cautela) {
        existingCautelaId = Number(cCheck.id_cautela);
      }
    }

    const payload = {
      id_policial: Number(polRow.id_policial),
      id_operador_entrega: cautela.id_operador_entrega,
      id_operador_devolucao: cautela.id_operador_devolucao || null,
      tipo: cautela.tipo,
      data_retirada: cautela.data_retirada,
      data_prevista_devolucao: cautela.data_prevista_devolucao || null,
      data_devolucao_efetiva: cautela.data_devolucao_efetiva || null,
      status: cautela.status,
      observacao: cautela.observacao || null,
    };

    let definitiveCautelaId: number;

    if (existingCautelaId) {
      const { data: updatedCautela, error: uErr } = await client
        .from('cautela')
        .update(payload)
        .eq('id_cautela', existingCautelaId)
        .select()
        .single();

      if (uErr) {
        console.error('[Supabase] Falha ao atualizar cautela:', uErr);
        return { success: false, error: uErr.message, code: uErr.code };
      }
      definitiveCautelaId = Number(updatedCautela.id_cautela);
    } else {
      const { data: insertedCautela, error: cErr } = await client
        .from('cautela')
        .insert(payload)
        .select()
        .single();

      if (cErr) {
        console.error('[Supabase] Falha ao inserir cautela:', cErr);
        return {
          success: false,
          error: `Falha ao registrar cautela no Supabase: ${cErr.message}`,
          code: cErr.code,
          details: cErr.details,
        };
      }
      definitiveCautelaId = Number(insertedCautela.id_cautela);
    }

    // 3. Insert items links and update item_patrimonio status to 'Cautelado'
    for (const itemLink of itens) {
      const { data: itemRow } = await client
        .from('item_patrimonio')
        .select('id_item')
        .eq('id_item', itemLink.id_item)
        .maybeSingle();

      if (itemRow?.id_item) {
        await client.from('cautela_item').upsert({
          id_cautela: definitiveCautelaId,
          id_item: Number(itemRow.id_item),
          observacao_estado_entrega: itemLink.observacao_estado_entrega || null,
          observacao_estado_devolucao: itemLink.observacao_estado_devolucao || null,
        }, { onConflict: 'id_cautela,id_item' });

        // Update item status in Supabase
        const targetStatus = cautela.status === 'Finalizada' ? 'Disponível' : 'Cautelado';
        await client
          .from('item_patrimonio')
          .update({ status: targetStatus })
          .eq('id_item', Number(itemRow.id_item));
      }
    }

    // 4. Insert lotes links and update estoque_lote stock
    for (const loteLink of lotes) {
      const { data: loteRow } = await client
        .from('estoque_lote')
        .select('id_lote, quantidade_atual')
        .eq('id_lote', loteLink.id_lote)
        .maybeSingle();

      if (loteRow?.id_lote) {
        await client.from('cautela_estoque').upsert({
          id_cautela: definitiveCautelaId,
          id_lote: Number(loteRow.id_lote),
          quantidade: loteLink.quantidade,
        }, { onConflict: 'id_cautela,id_lote' });

        // Update remaining stock in Supabase
        if (lotesSaldosRestantes && lotesSaldosRestantes.length > 0) {
          const spec = lotesSaldosRestantes.find((s) => s.id_lote === loteLink.id_lote);
          if (spec) {
            await client
              .from('estoque_lote')
              .update({ quantidade_atual: Math.max(0, spec.quantidade_atual) })
              .eq('id_lote', Number(loteRow.id_lote));
          }
        }
      }
    }

    return {
      success: true,
      data: { id_cautela: definitiveCautelaId },
      definitiveId: definitiveCautelaId,
    };
  } catch (err: any) {
    console.error('[Supabase] Exceção ao persistir cautela:', err);
    return { success: false, error: err.message };
  }
}

/**
 * Synchronizes the finalization (baixa) of a Cautela to Supabase.
 * - Updates cautela status to 'Finalizada', sets data_devolucao_efetiva and operator.
 * - Updates return observations on cautela_item.
 * - Restores or updates item_patrimonio status (Disponível, Manutenção, Extraviado).
 * - Restores returned ammunition/stock quantities on estoque_lote in the database.
 */
export async function finalizarCautelaInSupabase(params: {
  id_cautela: number;
  id_operador_devolucao?: string | null;
  data_devolucao_efetiva: string;
  observacao?: string | null;
  devolucoesItens: Array<{
    id_item: number;
    status_destino: string;
    observacao_estado_devolucao?: string;
    observacao_item?: string;
  }>;
  lotesAtualizados: Array<{
    id_lote: number;
    quantidade_atual: number;
  }>;
}): Promise<SyncOperationResult> {
  const client = getSupabaseClient();
  if (!client) return { success: false, error: 'Supabase não conectado' };

  try {
    // 1. Update Cautela in Supabase
    const { error: cautErr } = await client
      .from('cautela')
      .update({
        status: 'Finalizada',
        data_devolucao_efetiva: params.data_devolucao_efetiva,
        id_operador_devolucao: params.id_operador_devolucao || null,
        observacao: params.observacao || null,
      })
      .eq('id_cautela', params.id_cautela);

    if (cautErr) {
      console.error('[Supabase] Falha ao atualizar status da cautela:', cautErr);
      return { success: false, error: cautErr.message, code: cautErr.code };
    }

    // 2. Update cautela_item return notes and item_patrimonio statuses
    for (const dev of params.devolucoesItens) {
      if (dev.observacao_estado_devolucao) {
        await client
          .from('cautela_item')
          .update({
            observacao_estado_devolucao: dev.observacao_estado_devolucao,
          })
          .eq('id_cautela', params.id_cautela)
          .eq('id_item', dev.id_item);
      }

      const itemPayload: any = { status: dev.status_destino };
      if (dev.observacao_item) {
        itemPayload.observacao = dev.observacao_item;
      }
      await client
        .from('item_patrimonio')
        .update(itemPayload)
        .eq('id_item', dev.id_item);
    }

    // 3. Update estoque_lote quantities with restored values
    for (const lt of params.lotesAtualizados) {
      await client
        .from('estoque_lote')
        .update({
          quantidade_atual: Math.max(0, lt.quantidade_atual),
        })
        .eq('id_lote', lt.id_lote);
    }

    return { success: true };
  } catch (err: any) {
    console.error('[Supabase] Exceção ao finalizar cautela no banco:', err);
    return { success: false, error: err.message };
  }
}

