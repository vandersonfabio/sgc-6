/**
 * Uploads all local data to Supabase in strict dependency order:
 * 1. Unidades -> Maps local ID to DB ID
 * 2. Policiais -> Maps local ID to DB ID
 * 3. Operadores -> UUIDs linked to DB id_policial
 * 4. TiposMateriais -> Maps local ID to DB ID
 * 5. ItensPatrimonio -> Maps local ID to DB ID
 * 6. Detalhes (Armas, Coletes, IMPO, Com, Vtr, Inf) -> Linked to DB id_item
 * 7. Estoque Lotes -> Maps local ID to DB ID
 * 8. Cautelas + CautelaItens + CautelaEstoque
 * 9. Alocacoes + AlocacaoItens
 * 10. Auditoria
 */
export async function pushAllDataToSupabase(data: {
  unidades: Unidade[];
  policiais: Policial[];
  operadores: OperadorSistema[];
  tiposMateriais: TipoMaterial[];
  itens: ItemPatrimonio[];
  detalheArma: DetalheArma[];
  detalheColete: DetalheColete[];
  detalheImpo: DetalheImpo[];
  detalheComunicacao: DetalheComunicacao[];
  detalheViatura: DetalheViatura[];
  detalheInformatica: DetalheInformatica[];
  lotes: EstoqueLote[];
  cautelas: Cautela[];
  cautelaItens: CautelaItem[];
  cautelaEstoque: CautelaEstoque[];
  alocacoes: AlocacaoUnidade[];
  alocacaoItens: AlocacaoItem[];
  auditoriaLogs: AuditoriaLog[];
}): Promise<FullSyncResult> {
  const client = getSupabaseClient();
  if (!client) {
    return {
      success: false,
      message: 'Supabase não conectado',
      results: [{ entity: 'client', success: false, processed: 0, errors: 1, message: 'Cliente não configurado' }],
    };
  }

  const results: SyncEntityResult[] = [];
  const mapUnidadeId = new Map<number, number>();
  const mapPolicialId = new Map<number, number>();
  const mapTipoMaterialId = new Map<number, number>();
  const mapItemId = new Map<number, number>();
  const mapLoteId = new Map<number, number>();
  const mapCautelaId = new Map<number, number>();

  try {
    // 1. UNIDADES
    let unidadesProcessed = 0;
    let unidadesErrors = 0;
    for (const u of data.unidades) {
      const res = await pushUnidadeToSupabase(u);
      if (res.success && res.definitiveId) {
        mapUnidadeId.set(u.id_unidade, Number(res.definitiveId));
        unidadesProcessed++;
      } else {
        unidadesErrors++;
      }
    }
    results.push({
      entity: 'unidade',
      success: unidadesErrors === 0,
      processed: unidadesProcessed,
      errors: unidadesErrors,
      message: `${unidadesProcessed} unidades sincronizadas`,
    });

    // 2. TIPOS DE MATERIAL
    let tiposProcessed = 0;
    let tiposErrors = 0;
    for (const t of data.tiposMateriais) {
      const res = await pushTipoMaterialToSupabase(t);
      if (res.success && res.definitiveId) {
        mapTipoMaterialId.set(t.id_tipo_material, Number(res.definitiveId));
        tiposProcessed++;
      } else {
        tiposErrors++;
      }
    }
    results.push({
      entity: 'tipo_material',
      success: tiposErrors === 0,
      processed: tiposProcessed,
      errors: tiposErrors,
      message: `${tiposProcessed} tipos de materiais sincronizados`,
    });

    // 3. POLICIAIS
    let policiaisProcessed = 0;
    let policiaisErrors = 0;
    for (const p of data.policiais) {
      const resolvedUnit = p.id_unidade_lotacao ? mapUnidadeId.get(p.id_unidade_lotacao) || p.id_unidade_lotacao : null;
      const res = await pushPolicialToSupabase({ ...p, id_unidade_lotacao: resolvedUnit });
      if (res.success && res.definitiveId) {
        mapPolicialId.set(p.id_policial, Number(res.definitiveId));
        policiaisProcessed++;
      } else {
        policiaisErrors++;
      }
    }
    results.push({
      entity: 'policial',
      success: policiaisErrors === 0,
      processed: policiaisProcessed,
      errors: policiaisErrors,
      message: `${policiaisProcessed} policiais sincronizados`,
    });

    // 4. OPERADORES
    let opProcessed = 0;
    let opErrors = 0;
    for (const op of data.operadores) {
      const dbPolicialId = mapPolicialId.get(op.id_policial) || op.id_policial;
      const res = await pushOperadorToSupabase(op, dbPolicialId);

      if (res.success) {
        opProcessed++;
      } else {
        console.warn(`[Supabase] Erro ao sincronizar operador ${op.email}:`, res.error);
        opErrors++;
      }
    }
    results.push({
      entity: 'operador_sistema',
      success: opErrors === 0,
      processed: opProcessed,
      errors: opErrors,
      message: `${opProcessed} operadores sincronizados`,
    });

    // 5. ITENS PATRIMONIAIS & DETALHES
    let itensProcessed = 0;
    let itensErrors = 0;
    for (const it of data.itens) {
      const dbTipoId = it.id_tipo_material ? mapTipoMaterialId.get(it.id_tipo_material) || it.id_tipo_material : null;
      const arma = data.detalheArma.find((d) => d.id_item === it.id_item);
      const colete = data.detalheColete.find((d) => d.id_item === it.id_item);
      const impo = data.detalheImpo.find((d) => d.id_item === it.id_item);
      const comunicacao = data.detalheComunicacao.find((d) => d.id_item === it.id_item);
      const viatura = data.detalheViatura.find((d) => d.id_item === it.id_item);
      const informatica = data.detalheInformatica.find((d) => d.id_item === it.id_item);

      const res = await pushItemToSupabase(
        { ...it, id_tipo_material: dbTipoId },
        { arma, colete, impo, comunicacao, viatura, informatica }
      );

      if (res.success && res.definitiveId) {
        mapItemId.set(it.id_item, Number(res.definitiveId));
        itensProcessed++;
      } else {
        itensErrors++;
      }
    }
    results.push({
      entity: 'item_patrimonio',
      success: itensErrors === 0,
      processed: itensProcessed,
      errors: itensErrors,
      message: `${itensProcessed} itens patrimoniais sincronizados`,
    });

    // 6. ESTOQUE LOTES
    let lotesProcessed = 0;
    let lotesErrors = 0;
    for (const l of data.lotes) {
      const dbTipoId = l.id_tipo_material ? mapTipoMaterialId.get(l.id_tipo_material) || l.id_tipo_material : null;
      const res = await pushLoteToSupabase({ ...l, id_tipo_material: dbTipoId });
      if (res.success && res.definitiveId) {
        mapLoteId.set(l.id_lote, Number(res.definitiveId));
        lotesProcessed++;
      } else {
        lotesErrors++;
      }
    }
    results.push({
      entity: 'estoque_lote',
      success: lotesErrors === 0,
      processed: lotesProcessed,
      errors: lotesErrors,
      message: `${lotesProcessed} lotes de estoque sincronizados`,
    });

    // 7. CAUTELAS
    let cautelasProcessed = 0;
    let cautelasErrors = 0;
    for (const c of data.cautelas) {
      const dbPolicialId = mapPolicialId.get(c.id_policial) || c.id_policial;
      const linkedItens = data.cautelaItens
        .filter((ci) => ci.id_cautela === c.id_cautela)
        .map((ci) => ({
          ...ci,
          id_item: mapItemId.get(ci.id_item) || ci.id_item,
        }));
      const linkedLotes = data.cautelaEstoque
        .filter((ce) => ce.id_cautela === c.id_cautela)
        .map((ce) => ({
          ...ce,
          id_lote: mapLoteId.get(ce.id_lote) || ce.id_lote,
        }));

      const res = await pushCautelaToSupabase(
        { ...c, id_policial: dbPolicialId },
        linkedItens,
        linkedLotes
      );

      if (res.success && res.definitiveId) {
        mapCautelaId.set(c.id_cautela, Number(res.definitiveId));
        cautelasProcessed++;
      } else {
        cautelasErrors++;
      }
    }
    results.push({
      entity: 'cautela',
      success: cautelasErrors === 0,
      processed: cautelasProcessed,
      errors: cautelasErrors,
      message: `${cautelasProcessed} cautelas operacionais sincronizadas`,
    });

    const totalErrors = results.reduce((acc, r) => acc + r.errors, 0);
    const overallSuccess = totalErrors === 0;

    return {
      success: overallSuccess,
      message: overallSuccess
        ? 'Sincronização completa de todas as entidades concluída com sucesso no Supabase PostgreSQL!'
        : `Sincronização concluída com avisos/erros (${totalErrors} registro(s) com falha). Verifique o detalhamento.`,
      results,
    };
  } catch (err: any) {
    console.error('[Supabase] Exceção na sincronização completa:', err);
    return {
      success: false,
      message: `Erro fatal durante sincronização: ${err.message}`,
      results,
    };
  }
}

